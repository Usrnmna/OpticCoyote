inline uint8_t glyphIndex(char symbol) {
  if (symbol >= '0' && symbol <= '9') return symbol - '0';
  if (symbol == '.') return 11;
  if (symbol == DisplayProtocol::kAtLeastGlyph) return 12;
  return 10;  // Unrecognized symbols use the unavailable dash.
}

inline uint8_t glyphWidth(char symbol) {
  return symbol == '.' ? kDotWidth : kDigitWidth;
}

// The formatter always supplies three symbols. Narrow decimal points produce
// 23-pixel fields; the capped value occupies 29 pixels. Center both in 32 pixels.
inline uint8_t valueWidth(const char (&text)[5]) {
  return glyphWidth(text[0]) + glyphWidth(text[1]) + glyphWidth(text[2]) +
      2 * kSpacing;
}

// Draw into the cleared framebuffer; no heap allocation or per-glyph transfer.
// The private '>' token selects the complete >= symbol, not the default font.
template <typename Display>
void drawValue(Display &display, uint8_t columnLeft, const char (&text)[5]) {
  uint8_t left = columnLeft + (kColumnWidth - valueWidth(text)) / 2;
  for (uint8_t symbol = 0; symbol < 3; ++symbol) {
    const uint8_t index = glyphIndex(text[symbol]);
    const uint8_t width = glyphWidth(text[symbol]);
    for (uint8_t row = 0; row < kHeight; ++row) {
      const uint16_t bits = pgm_read_word(&kRows[index][row]);
      for (uint8_t column = 0; column < width; ++column) {
        if (bits & (0x100U >> column))
          display.drawPixel(left + column, kValueTop + row, 1);
      }
    }
    left += width + kSpacing;
  }
}
