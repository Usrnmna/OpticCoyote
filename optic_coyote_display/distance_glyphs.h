constexpr uint8_t kSpacing = 1;
static_assert(3 * kDigitWidth + 2 * kSpacing <= kColumnWidth,
              "The capped distance must fit one sensor column");
static_assert(kValueTop + kHeight <= 24, "Leave row 24 clear above the footer");

